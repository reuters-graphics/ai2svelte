#!/usr/bin/env node
// Builds the feature fixtures by scripting real Illustrator, so the .ai files
// are reproducible instead of hand-drawn:
//   presets.ai  every shadow + animation preset, custom SCSS, a missing style
//   layers.ai   :div / :symbol / :png / :svg / :snippet layers, data-attribute
//               notes, fixed-width and image_only artboard tags, a mapped font
// Writes them to src/js/main/example/ plus styles/presets.scss (the SCSS a user
// would type into the Styles tab, one rule per preset). Local-only: needs
// Illustrator. Re-run when the preset library changes, then regenerate baselines.
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import JSON5 from "json5";
import { closeStyles, toCamelCase } from "./styles.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(here, "../..");
const exampleDir = path.join(rootDir, "src/js/main/example");
const dataDir = path.join(rootDir, "src/js/main/Tabs/data");

const animations = JSON5.parse(readFileSync(path.join(dataDir, "animations.json"), "utf8"));
const shadows = JSON5.parse(readFileSync(path.join(dataDir, "shadows.json"), "utf8"));
const byCandidate = (c) => animations.filter((a) => a.candidate === c);

// ---------- presets.scss ----------
const animRule = (selector, a) =>
  `${selector} {\n  @include animation-${a.name}();\n  animation: ${a.animationRule};\n}`;
const shapeAnims = byCandidate("shape");
const lineAnims = byCandidate("line");
const textAnims = byCandidate("text");

const scss = [
  "// One rule per shadow/animation preset, plus custom SCSS and a missing style.",
  "// Generated by build-ai-fixtures.mjs: edit there, not here.",
  ...(await Promise.all(
    shadows.map(
      async (s, i) =>
        `#g-s${i} {\n  @include shadow-${await toCamelCase(s.id)}(#000000);\n}`,
    ),
  )),
  ...shapeAnims.map((a, i) => animRule(`#g-div-shapes-a${i}`, a)),
  ...lineAnims.map((a, i) => animRule(`#g-svg-lines #l${i}`, a)),
  ...textAnims.map((a, i) => animRule(`#g-t${i}`, a)),
  // custom SCSS: variables, maps, @function, @mixin, nesting, @each, @if, math
  `$accent: #e11d48;
$sizes: (sm: 4px, md: 8px, lg: 16px);
@function double($n) { @return $n * 2; }
@mixin card($c, $radius: 8px) {
  background-color: $c;
  border-radius: double($radius);
}
#g-div-custom-c0 {
  @include card($accent);
  &:hover { opacity: 0.5; }
}
#g-div-custom-c1 {
  @each $k, $v in $sizes {
    --size-#{$k}: #{$v};
  }
  @include card(#2563eb, 4px);
  border: var(--size-lg) solid #facc15;
  @if double(2) == 4 { outline: 3px dotted #ffffff; }
}`,
  // library lookups that fail export as empty mixins, not errors
  `#g-div-custom-c2 {
  @include card(#10b981, 0px);
  @include animation-notInLibrary();
  @include shadow-notInLibrary(#000000);
}`,
].join("\n\n");
mkdirSync(path.join(here, "styles"), { recursive: true });
writeFileSync(path.join(here, "styles/presets.scss"), scss + "\n");
await closeStyles();

// ---------- Illustrator ----------
const COMMON = `
// artboard top in document coordinates (y grows upward; new docs start at 0..height)
var TOP = 0;
function rgb(r, g, b) { var c = new RGBColor(); c.red = r; c.green = g; c.blue = b; return c; }
function layer(doc, name) {
  try { return doc.layers.getByName(name); } catch (e) {}
  var l = doc.layers.add(); l.name = name; return l;
}
function rect(l, name, x, y, w, h, fill) {
  var r = l.pathItems.rectangle(TOP - y, x, w, h); r.name = name; r.stroked = false;
  r.filled = true; r.fillColor = fill; return r;
}
function save(doc, file) {
  var o = new IllustratorSaveOptions(); o.pdfCompatible = false;
  doc.saveAs(new File(file), o);
  doc.close(SaveOptions.DONOTSAVECHANGES);
}
function text(l, name, str, x, y, size, fill) {
  var t = l.textFrames.add(); t.contents = str; t.name = name; t.position = [x, TOP - y];
  var a = t.textRange.characterAttributes; a.size = size; a.fillColor = fill;
  try { a.textFont = app.textFonts.getByName("ArialMT"); } catch (e) {}
  return t;
}
`;

const presetsJsx = `
${COMMON}
var shadowCount = ${shadows.length}, shapeCount = ${shapeAnims.length},
    lineCount = ${lineAnims.length}, textCount = ${textAnims.length};
var doc = app.documents.add(DocumentColorSpace.RGB, 800, 740);
TOP = doc.artboards[0].artboardRect[1];
doc.layers[0].name = "bg";
rect(doc.layers[0], "bgrect", 0, 0, 800, 740, rgb(110, 120, 140));
var white = rgb(255, 255, 255);

// shadows: untagged text, one per preset, white on grey so a black shadow reads
var sh = layer(doc, "shadows");
for (var i = 0; i < shadowCount; i++) {
  text(sh, "s" + i, "Aa Bb", 20 + (i % 6) * 128, 20 + Math.floor(i / 6) * 50, 26, white);
}
// shape animations: :div rects
var shapes = layer(doc, "shapes:div");
for (i = 0; i < shapeCount; i++) {
  rect(shapes, "a" + i, 30 + (i % 8) * 95, 300 + Math.floor(i / 8) * 90, 50, 50, rgb(250, 160, 40));
}
// line animations: stroked open paths in an :svg layer
var lines = layer(doc, "lines:svg");
for (i = 0; i < lineCount; i++) {
  var p = lines.pathItems.add(); p.name = "l" + i;
  p.setEntirePath([[30 + i * 270, TOP - 500], [230 + i * 270, TOP - 500]]);
  p.filled = false; p.stroked = true; p.strokeColor = white; p.strokeWidth = 4;
}
// text animations
var at = layer(doc, "animtext");
for (i = 0; i < textCount; i++) text(at, "t" + i, "Animated " + i, 30 + i * 270, 540, 24, white);
// custom SCSS targets
var custom = layer(doc, "custom:div");
for (i = 0; i < 3; i++) rect(custom, "c" + i, 30 + i * 260, 620, 220, 70, rgb(60, 60, 60));
save(doc, ${JSON.stringify(path.join(exampleDir, "presets.ai"))});
`;

const layersJsx = `
${COMMON}
// wide first, as users often order them (an early build once lost the wide artboard's HTML with this order)
var doc = app.documents.add(DocumentColorSpace.RGB, 800, 500);
TOP = doc.artboards[0].artboardRect[1];
doc.layers[0].name = "bg";
doc.artboards[0].name = "wide:600,fixed";
doc.artboards.add([900, TOP, 1300, TOP - 250]);
doc.artboards[1].name = "narrow:image_only";

function noted(item, note) { item.note = note; return item; }
function build(ox, s) {
  function X(x) { return ox + x * s; }
  function Y(y) { return y * s; }
  function R(l, n, x, y, w, h, c) { return rect(l, n, X(x), Y(y), w * s, h * s, c); }
  var dark = rgb(30, 30, 30);

  R(layer(doc, "bg"), "bgrect", 0, 0, 800, 500, rgb(235, 238, 245));

  var blocks = layer(doc, "blocks:div");
  noted(R(blocks, "b0", 40, 40, 200, 120, rgb(225, 29, 72)), "category: road\\ncolor: orange");
  noted(R(blocks, "b1", 260, 40, 200, 120, rgb(37, 99, 235)), "category: rail");
  var hid = noted(R(blocks, "bh", 480, 40, 60, 120, rgb(0, 0, 0)), "hidden: yes");
  hid.hidden = true;

  var pins = layer(doc, "pins:symbol");
  var e0 = pins.pathItems.ellipse(TOP - Y(70), X(550), 60 * s, 60 * s); e0.name = "p0";
  e0.fillColor = rgb(16, 185, 129); e0.stroked = false; noted(e0, "kind: pin");
  var e1 = pins.pathItems.ellipse(TOP - Y(70), X(650), 60 * s, 60 * s); e1.name = "p1";
  e1.fillColor = rgb(245, 158, 11); e1.stroked = false;

  var raster = layer(doc, "raster:png");
  var re = raster.pathItems.ellipse(TOP - Y(230), X(60), 140 * s, 140 * s); re.name = "r0";
  re.fillColor = rgb(147, 51, 234); re.stroked = true; re.strokeColor = dark; re.strokeWidth = 6 * s;
  noted(re, "src: raster");
  noted(R(raster, "r1", 220, 260, 80, 80, rgb(20, 184, 166)), "layer: raster2");

  var vec = layer(doc, "vec:svg");
  var v0 = vec.pathItems.add(); v0.name = "v0";
  v0.setEntirePath([[X(340), TOP - Y(260)], [X(520), TOP - Y(340)]]);
  v0.filled = false; v0.stroked = true; v0.strokeColor = rgb(220, 38, 38); v0.strokeWidth = 6 * s;
  noted(v0, "series: a");
  var v1 = vec.pathItems.rectangle(TOP - Y(260), X(540), 100 * s, 80 * s); v1.name = "v1";
  v1.filled = false; v1.stroked = true; v1.strokeColor = rgb(37, 99, 235); v1.strokeWidth = 6 * s;
  noted(v1, "series: b");

  noted(R(layer(doc, "slot:snippet"), "slotbox", 660, 260, 100, 80, rgb(0, 0, 0)), "slot: main");

  var label = layer(doc, "label");
  noted(text(label, "title", "Layers fixture", X(40), Y(400), 28 * s, dark), "role: title");
  text(label, "caption", "Tags, notes and artboards", X(40), Y(445), 16 * s, dark);
}
build(0, 1);
build(900, 0.5);
save(doc, ${JSON.stringify(path.join(exampleDir, "layers.ai"))});
`;

function run(name, jsx) {
  const f = path.join(os.tmpdir(), `ai2svelte-build-${name}.jsx`);
  writeFileSync(f, `#target illustrator\napp.userInteractionLevel = UserInteractionLevel.DONTDISPLAYALERTS;\n(function(){${jsx}})();`);
  console.log(`[${name}] building in Illustrator...`);
  execFileSync(
    "osascript",
    ["-e", `with timeout of 300 seconds\ntell application "Adobe Illustrator" to do javascript (POSIX file "${f}")\nend timeout`],
    { stdio: "inherit" },
  );
}
// optional names: `node build-ai-fixtures.mjs layers` rebuilds just that one
const only = process.argv.slice(2);
if (!only.length || only.includes("presets")) run("presets", presetsJsx);
if (!only.length || only.includes("layers")) run("layers", layersJsx);
console.log("done: presets.ai, layers.ai, styles/presets.scss");
process.exit(0); // the Vite server from styles.mjs would otherwise keep the process alive
