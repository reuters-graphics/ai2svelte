// use_lazy_loader: <script> code emitted into the generated component when it
// has lazy images. Its own module so the Vitest suite can mount it for real
// (src/js/main/__tests__/lazyScript.test.ts).
//
// seen holds ids of images that have neared the viewport. The lazy attachment
// observes each image while it's mounted, so artboards swapped in by {#if} are
// covered; display:none artboards never intersect.
//
// An IntersectionObserver clips each target by every clipping ancestor
// (overflow, contain: paint) before rootMargin applies, so lazyMargin can't
// reach past one: a wide graphic panned inside such an ancestor loads tiles
// only once they're on screen. reveal() and getLazyTiles() let the host page
// drive loading itself there; check() does it by position using lazyMargin.
export var LAZY_SCRIPT = [
  "\tlet seen = $state({});",
  "\tlet io;",
  "\tconst pending = new Set();",
  "",
  "\tfunction lazy(el) {",
  "\t\tio ??= new IntersectionObserver(",
  "\t\t\t(entries) => {",
  "\t\t\t\tfor (const e of entries) {",
  "\t\t\t\t\tif (e.isIntersecting) {",
  "\t\t\t\t\t\tseen[e.target.id] = true;",
  "\t\t\t\t\t\tpending.delete(e.target);",
  "\t\t\t\t\t\tio.unobserve(e.target);",
  "\t\t\t\t\t}",
  "\t\t\t\t}",
  "\t\t\t},",
  "\t\t\t{ root: lazyRoot, rootMargin: lazyMargin },",
  "\t\t);",
  "\t\tpending.add(el);",
  "\t\tio.observe(el);",
  "\t\treturn () => {",
  "\t\t\tpending.delete(el);",
  "\t\t\tio.unobserve(el);",
  "\t\t};",
  "\t}",
  "",
  "\t// load these images now (an id or an array of ids), e.g. when a clipping",
  "\t// ancestor stops lazyMargin from loading them ahead of the screen",
  "\texport function reveal(ids) {",
  "\t\tfor (const id of [ids].flat()) seen[id] = true;",
  "\t\tfor (const el of pending) {",
  "\t\t\tif (seen[el.id]) {",
  "\t\t\t\tpending.delete(el);",
  "\t\t\t\tio.unobserve(el);",
  "\t\t\t}",
  "\t\t}",
  "\t}",
  "",
  "\t// reveal() pending images within lazyMargin of the viewport (or lazyRoot),",
  "\t// by their real position: unlike the observer, it ignores clipping",
  "\t// ancestors. Call it whenever the graphic moves, e.g. each frame of a pan",
  "\texport function check() {",
  "\t\tconst [t, r = t, b = t, l = r] = lazyMargin.trim().split(/\\s+/);",
  "\t\tconst box = lazyRoot?.getBoundingClientRect() ?? {",
  "\t\t\tleft: 0, top: 0, right: innerWidth, bottom: innerHeight,",
  "\t\t\twidth: innerWidth, height: innerHeight,",
  "\t\t};",
  "\t\tconst px = (v, size) =>",
  "\t\t\tv.endsWith('%') ? (parseFloat(v) / 100) * size : parseFloat(v);",
  "\t\tconst ids = [];",
  "\t\tfor (const el of pending) {",
  "\t\t\tconst q = el.getBoundingClientRect();",
  "\t\t\t// zero size: display:none (an inactive artboard), never loads",
  "\t\t\tif (!q.width && !q.height) continue;",
  "\t\t\tif (",
  "\t\t\t\tq.bottom >= box.top - px(t, box.height) &&",
  "\t\t\t\tq.left <= box.right + px(r, box.width) &&",
  "\t\t\t\tq.top <= box.bottom + px(b, box.height) &&",
  "\t\t\t\tq.right >= box.left - px(l, box.width)",
  "\t\t\t)",
  "\t\t\t\tids.push(el.id);",
  "\t\t}",
  "\t\treveal(ids);",
  "\t}",
  "",
  "\t// mounted images still waiting to load, as { id, el }",
  "\texport function getLazyTiles() {",
  "\t\treturn [...pending].map((el) => ({ id: el.id, el }));",
  "\t}",
  "",
].join("\r");
